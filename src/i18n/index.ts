type TranslationKey = keyof typeof dictionary.es;

export function t(language: Language, key: TranslationKey, params: Record<string, string | number> = {}) {
  let value: string = dictionary[language][key] ?? dictionary.es[key];
  for (const [param, replacement] of Object.entries(params)) {
    value = value.replace(`{${param}}`, String(replacement));
  }
  return value;
}
